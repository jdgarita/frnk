import java.util.Properties

plugins {
    id("frnk.kmp.library.hosttest")
}

// The toolkit-wide PostHog project key is a build-time input, never a committed constant: every frnk
// app reports to the one project, so the key ships INSIDE the toolkit's binaries (Android AAR + the
// iOS klib every umbrella framework links), and no host supplies it — but this repo will be public,
// so the value lives in the gitignored `local.properties` of the frnk checkout (the submodule's, in
// a host), or in the `POSTHOG_API_KEY` env var / `-PPOSTHOG_API_KEY=` Gradle property for CI.
// `generateFrnkPostHogProject` writes it into `FrnkPostHogProject` under build/ and fails loudly when
// every source is blank. A `phc_…` project key is a public client key by design (it is embedded in
// every shipped binary and grants no read access) — the reason it can live in a binary at all.
val localProperties: Provider<Properties> =
    providers
        .fileContents(rootProject.layout.projectDirectory.file("local.properties"))
        .asText
        .map { text -> Properties().apply { load(text.reader()) } }
        .orElse(Properties())

fun buildInput(name: String): Provider<String> =
    providers
        .gradleProperty(name)
        .orElse(providers.environmentVariable(name))
        .orElse(localProperties.map { it.getProperty(name, "") })
        .map { it.trim() }

val generateFrnkPostHogProject by tasks.registering(GenerateFrnkPostHogProject::class) {
    apiKey.set(buildInput("POSTHOG_API_KEY"))
    host.set(buildInput("POSTHOG_HOST"))
    outputDir.set(layout.buildDirectory.dir("generated/frnkPostHog/commonMain/kotlin"))
}

kotlin {
    android {
        namespace = "${libs.versions.frnk.groupId.get()}.backend.posthog"
    }
    sourceSets {
        commonMain {
            kotlin.srcDir(generateFrnkPostHogProject)
            dependencies {
                api(projects.analyticsApi)
                implementation(libs.koin.core)
                implementation(libs.posthog.kmp)
            }
        }
        // PostHog's Android setup needs the Application; it comes from Koin's androidContext(),
        // which the Android initializeFrnk overload registers.
        androidMain.dependencies {
            implementation(libs.koin.android)
        }
    }
}

