@CacheableTask
abstract class GenerateFrnkPostHogProject : DefaultTask() {
    @get:Input
    abstract val apiKey: Property<String>

    @get:Input
    abstract val host: Property<String>

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val key = apiKey.get()
        check(key.isNotBlank()) {
            "POSTHOG_API_KEY is not set — frnk ships the toolkit-wide PostHog project key inside " +
                ":analytics-posthog, read at build time from the frnk checkout's local.properties " +
                "(gitignored; see local.properties.example), the POSTHOG_API_KEY environment variable, " +
                "or -PPOSTHOG_API_KEY=… . Hosts never pass it in code."
        }
        check(key.startsWith("phc_")) { "POSTHOG_API_KEY must be a PostHog project API key (phc_…), got '${key.take(4)}…'" }
        val hostExpr = host.get().ifBlank { "" }.let { if (it.isBlank()) "PostHogConfig.HOST_US" else "\"$it\"" }
        val file = outputDir.get().asFile.resolve("dev/jdgarita/frnk/backend/posthog/FrnkPostHogProject.kt")
        file.parentFile.mkdirs()
        file.writeText(
            """
            |package dev.jdgarita.frnk.backend.posthog
            |
            |import com.posthog.kmp.PostHogConfig
            |
            |/**
            | * GENERATED by `:analytics-posthog`'s `generateFrnkPostHogProject` from `POSTHOG_API_KEY` /
            | * `POSTHOG_HOST` (frnk's gitignored `local.properties`, or the env var / `-P` property). Do not edit,
            | * do not commit a copy.
            | *
            | * The one PostHog project every frnk host reports to. Its API key is universal across the apps —
            | * it identifies the project, not an app — so it ships inside the toolkit's binaries and a host never
            | * supplies it: [PostHogAnalyticsConfig.apiKey] defaults to [API_KEY]. Apps are told apart inside
            | * PostHog by the SDK's `${'$'}app_namespace` / `${'$'}app_name` properties, debug vs release by the
            | * `environment` super property. A `phc_…` key is a public client key by design; the project's
            | * secret keys never enter the toolkit. Contrast Sentry: each app has its own project + DSN.
            | */
            |object FrnkPostHogProject {
            |    /** Project API key of the shared frnk PostHog project. */
            |    const val API_KEY: String = "$key"
            |
            |    /** Ingestion host of the project's region. */
            |    const val HOST: String = $hostExpr
            |}
            |
            """.trimMargin()
        )
    }
}